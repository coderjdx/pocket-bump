IGNORED_EXACT = {
    "sw.js",
    "flutter_service_worker.js",
    ".last_build_id",
    ".nojekyll",
    "assets/NOTICES",
}


def should_ignore(rel_path: str) -> bool:
    if rel_path in IGNORED_EXACT:
        return True
    if rel_path.endswith(".map") or rel_path.endswith(".symbols"):
        return True
    if rel_path.startswith("canvaskit/skwasm") or rel_path.startswith("canvaskit/wimp"):
        return True
    if rel_path.startswith("canvaskit/webparagraph/"):
        return True
    return False


def file_sha256_8(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()[:8]


def collect_files(web_dir: Path, version: str):
    core_assets = ["./"]
    canvaskit_default = []
    canvaskit_chromium = []
    asset_manifest = {}
    digest_inputs = [f"version:{version}"]

    for root, dirs, files in os.walk(web_dir):
        dirs.sort()
        files.sort()
        for fname in files:
            full_path = Path(root) / fname
            rel_path = full_path.relative_to(web_dir).as_posix()
            if should_ignore(rel_path):
                continue

            digest = file_sha256_8(full_path)
            digest_inputs.append(f"{rel_path}:{digest}")

            if rel_path in ("canvaskit/canvaskit.js", "canvaskit/canvaskit.wasm"):
                canvaskit_default.append(rel_path)
            elif rel_path in (
                "canvaskit/chromium/canvaskit.js",
                "canvaskit/chromium/canvaskit.wasm",
            ):
                canvaskit_chromium.append(rel_path)
            elif rel_path.startswith("assets/assets/"):
                asset_manifest[rel_path] = digest
            else:
                core_assets.append(rel_path)

    build_hash_input = "\n".join(sorted(digest_inputs)).encode("utf-8")
    build_hash = hashlib.sha256(build_hash_input).hexdigest()[:8]
    return core_assets, canvaskit_default, canvaskit_chromium, asset_manifest, build_hash


def build_sw_js(
    cache_version: str,
    core_assets: list,
    canvaskit_default: list,
    canvaskit_chromium: list,
    asset_manifest: dict,
) -> str:
    return f"""// Generated by tool/build_pwa.py — do not edit manually.
const CACHE_VERSION = {json.dumps(cache_version)};
const APP_CACHE = "pocket-bump-app-" + CACHE_VERSION;
const ASSET_CACHE = "pocket-bump-assets-v1";
const FONT_CACHE = "pocket-bump-fonts-v1";

const CORE_ASSETS = {json.dumps(core_assets, indent=2)};
const CANVASKIT_DEFAULT = {json.dumps(canvaskit_default, indent=2)};
const CANVASKIT_CHROMIUM = {json.dumps(canvaskit_chromium, indent=2)};
const ASSET_MANIFEST = {json.dumps(asset_manifest, indent=2)};

let precachePromise = null;

function getRuntimeCanvaskitAssets() {{
  const ua = (self.navigator && self.navigator.userAgent) || "";
  const isNonIosChromium =
    /Chrome|Chromium|Edg/i.test(ua) &&
    !/iPhone|iPad|iPod|CriOS|FxiOS|EdgiOS/i.test(ua);
  if (isNonIosChromium && CANVASKIT_CHROMIUM.length > 0) {{
    return CANVASKIT_CHROMIUM;
  }}
  return CANVASKIT_DEFAULT;
}}

function toScopeUrl(relPath) {{
  return new URL(relPath, self.registration.scope).href;
}}

function assetCacheKey(relPath, hash) {{
  return toScopeUrl(relPath) + "?v=" + hash;
}}

async function broadcast(msg) {{
  try {{
    const clients = await self.clients.matchAll({{
      type: "window",
      includeUncontrolled: true
    }});
    for (let i = 0; i < clients.length; i++) {{
      clients[i].postMessage(msg);
    }}
  }} catch (_) {{}}
}}

async function cacheCoreShell() {{
  const cache = await caches.open(APP_CACHE);
  const targets = CORE_ASSETS.concat(getRuntimeCanvaskitAssets());
  const concurrency = 6;
  let index = 0;

  async function worker() {{
    while (index < targets.length) {{
      const relPath = targets[index++];
      const url = toScopeUrl(relPath);
      const reqPath = relPath === "./" ? "index.html" : relPath;
      const res = await fetch(toScopeUrl(reqPath), {{ cache: "no-cache" }});
      if (!res || !res.ok) {{
        throw new Error("Failed core precache: " + relPath + " (" + (res && res.status) + ")");
      }}
      await cache.put(url, res.clone());
      if (relPath === "index.html") {{
        await cache.put(toScopeUrl("./"), res.clone());
      }}
    }}
  }}

  const workers = [];
  for (let i = 0; i < Math.min(concurrency, targets.length); i++) {{
    workers.push(worker());
  }}
  await Promise.all(workers);
}}

async function precacheAllAssets() {{
  if (precachePromise) {{
    return precachePromise;
  }}

  precachePromise = (async function() {{
    const entries = Object.entries(ASSET_MANIFEST);
    const total = entries.length;
    if (total === 0) {{
      await broadcast({{ type: "PRECACHE_DONE", total: 0, cached: 0, downloaded: 0 }});
      return;
    }}

    const cache = await caches.open(ASSET_CACHE);
    const existingKeys = await cache.keys();
    const existingSet = new Set();
    for (let i = 0; i < existingKeys.length; i++) {{
      existingSet.add(existingKeys[i].url);
    }}

    const missing = [];
    for (let i = 0; i < entries.length; i++) {{
      const relPath = entries[i][0];
      const hash = entries[i][1];
      const keyUrl = assetCacheKey(relPath, hash);
      if (!existingSet.has(keyUrl)) {{
        missing.push([relPath, hash, keyUrl]);
      }}
    }}

    const alreadyCached = total - missing.length;
    if (missing.length === 0) {{
      await broadcast({{ type: "PRECACHE_DONE", total: total, cached: total, downloaded: 0 }});
      return;
    }}

    let downloaded = 0;
    let processed = 0;
    let cursor = 0;
    const batchSize = 8;

    async function worker() {{
      while (cursor < missing.length) {{
        const item = missing[cursor++];
        const relPath = item[0];
        const keyUrl = item[2];
        try {{
          const res = await fetch(toScopeUrl(relPath), {{ cache: "no-cache" }});
          if (res && res.ok && res.status === 200) {{
            try {{
              await cache.put(keyUrl, res.clone());
              downloaded++;
            }} catch (_) {{}}
          }}
        }} catch (_) {{}}
        processed++;
        if (processed % 10 === 0 || processed === missing.length) {{
          await broadcast({{
            type: "PRECACHE_PROGRESS",
            cached: alreadyCached + downloaded,
            total: total,
            downloaded: downloaded
          }});
        }}
      }}
    }}

    const workers = [];
    for (let i = 0; i < Math.min(batchSize, missing.length); i++) {{
      workers.push(worker());
    }}
    await Promise.all(workers);

    await broadcast({{
      type: "PRECACHE_DONE",
      total: total,
      cached: alreadyCached + downloaded,
      downloaded: downloaded
    }});
  }})().finally(function() {{
    precachePromise = null;
  }});

  return precachePromise;
}}

async function pruneOldCaches() {{
  const keys = await caches.keys();
  const allowed = new Set([APP_CACHE, ASSET_CACHE, FONT_CACHE]);
  await Promise.all(
    keys.map(function(key) {{
      if (!allowed.has(key)) {{
        return caches.delete(key);
      }}
      return Promise.resolve(false);
    }})
  );

  const assetCache = await caches.open(ASSET_CACHE);
  const validUrls = new Set();
  const entries = Object.entries(ASSET_MANIFEST);
  for (let i = 0; i < entries.length; i++) {{
    validUrls.add(assetCacheKey(entries[i][0], entries[i][1]));
  }}
  const cachedReqs = await assetCache.keys();
  await Promise.all(
    cachedReqs.map(function(req) {{
      if (!validUrls.has(req.url)) {{
        return assetCache.delete(req);
      }}
      return Promise.resolve(false);
    }})
  );
}}

async function createRangeResponse(request, cachedResponse) {{
  const rangeHeader = request.headers.get("range") || "";
  const match = /^bytes=(\\d*)-(\\d*)$/i.exec(rangeHeader.trim());
  const buf = await cachedResponse.arrayBuffer();
  const total = buf.byteLength;
  if (!match) {{
    return cachedResponse;
  }}

  let start = match[1] ? parseInt(match[1], 10) : 0;
  let end = match[2] ? parseInt(match[2], 10) : total - 1;
  if (!match[1] && match[2]) {{
    start = Math.max(0, total - parseInt(match[2], 10));
    end = total - 1;
  }}
  if (Number.isNaN(start) || Number.isNaN(end) || start > end || start >= total) {{
    return new Response(null, {{
      status: 416,
      statusText: "Range Not Satisfiable",
      headers: {{ "Content-Range": "bytes */" + total }}
    }});
  }}
  end = Math.min(end, total - 1);

  const sliced = buf.slice(start, end + 1);
  const headers = new Headers(cachedResponse.headers);
  headers.set("Content-Range", "bytes " + start + "-" + end + "/" + total);
  headers.set("Content-Length", String(sliced.byteLength));
  headers.set("Accept-Ranges", "bytes");
  return new Response(sliced, {{
    status: 206,
    statusText: "Partial Content",
    headers: headers
  }});
}}

self.addEventListener("install", function(event) {{
  event.waitUntil(
    cacheCoreShell().then(function() {{
      return self.skipWaiting();
    }})
  );
}});

self.addEventListener("activate", function(event) {{
  event.waitUntil(
    pruneOldCaches()
      .then(function() {{
        return self.clients.claim();
      }})
      .then(function() {{
        precacheAllAssets();
      }})
  );
}});

self.addEventListener("message", function(event) {{
  const data = event.data || {{}};
  if (data.type === "SKIP_WAITING") {{
    self.skipWaiting();
  }} else if (data.type === "PRECACHE_ALL") {{
    event.waitUntil(precacheAllAssets());
  }} else if (data.type === "GET_VERSION") {{
    const reply = {{ type: "VERSION", version: CACHE_VERSION }};
    if (event.ports && event.ports[0]) {{
      event.ports[0].postMessage(reply);
    }} else if (event.source && typeof event.source.postMessage === "function") {{
      event.source.postMessage(reply);
    }}
  }}
}});

async function handleFontFetch(request) {{
  const cache = await caches.open(FONT_CACHE);
  const cached = await cache.match(request);
  if (cached) {{
    return cached;
  }}
  const res = await fetch(request);
  if (res && (res.ok || res.type === "opaque")) {{
    try {{
      await cache.put(request, res.clone());
    }} catch (_) {{}}
  }}
  return res;
}}

async function handleNavigationFetch(relPath) {{
  const cache = await caches.open(APP_CACHE);
  const targetRel = relPath === "" ? "index.html" : relPath;
  try {{
    const res = await fetch(toScopeUrl(targetRel), {{ cache: "no-cache" }});
    if (res && res.ok) {{
      try {{
        await cache.put(toScopeUrl("index.html"), res.clone());
        await cache.put(toScopeUrl("./"), res.clone());
      }} catch (_) {{}}
      return res;
    }}
  }} catch (_) {{}}
  return (
    (await cache.match(toScopeUrl("index.html"))) ||
    (await cache.match(toScopeUrl("./"))) ||
    Response.error()
  );
}}

async function handleBundledAssetFetch(request, relPath) {{
  const hash = ASSET_MANIFEST[relPath];
  const key = assetCacheKey(relPath, hash);
  const cache = await caches.open(ASSET_CACHE);
  const cached = await cache.match(key);
  if (cached) {{
    if (request.headers.has("range")) {{
      return createRangeResponse(request, cached);
    }}
    return cached;
  }}

  const res = await fetch(toScopeUrl(relPath));
  if (res && res.ok && res.status === 200) {{
    try {{
      await cache.put(key, res.clone());
    }} catch (_) {{}}
    if (request.headers.has("range")) {{
      return createRangeResponse(request, res);
    }}
  }}
  return res;
}}

async function handleNetworkFirstShell(relPath) {{
  const cache = await caches.open(APP_CACHE);
  const url = toScopeUrl(relPath);
  try {{
    const res = await fetch(url, {{ cache: "no-cache" }});
    if (res && res.ok) {{
      try {{
        await cache.put(url, res.clone());
      }} catch (_) {{}}
      return res;
    }}
  }} catch (_) {{}}
  return (await cache.match(url)) || Response.error();
}}

async function handleCacheFirstShell(request, relPath) {{
  const cache = await caches.open(APP_CACHE);
  const key = toScopeUrl(relPath);
  const cached = await cache.match(key);
  if (cached) {{
    return cached;
  }}
  const res = await fetch(request);
  if (res && res.ok && res.status === 200) {{
    try {{
      await cache.put(key, res.clone());
    }} catch (_) {{}}
  }}
  return res;
}}

self.addEventListener("fetch", function(event) {{
  const request = event.request;
  if (request.method !== "GET") {{
    return;
  }}

  const url = new URL(request.url);
  if (url.protocol !== "http:" && url.protocol !== "https:") {{
    return;
  }}

  if (url.origin !== self.location.origin) {{
    if (
      url.hostname === "fonts.gstatic.com" ||
      url.hostname === "fonts.googleapis.com"
    ) {{
      event.respondWith(handleFontFetch(request));
    }}
    return;
  }}

  const scopePath = new URL(self.registration.scope).pathname;
  if (
    !url.pathname.startsWith(scopePath) &&
    url.pathname + "/" !== scopePath
  ) {{
    return;
  }}

  let relPath = "";
  if (url.pathname.startsWith(scopePath)) {{
    relPath = url.pathname.slice(scopePath.length);
  }}
  relPath = relPath.replace(/^\\/+/, "");
  if (relPath === "") {{
    relPath = "index.html";
  }}

  if (request.mode === "navigate" || relPath === "index.html") {{
    event.respondWith(handleNavigationFetch(relPath));
    return;
  }}

  if (Object.prototype.hasOwnProperty.call(ASSET_MANIFEST, relPath)) {{
    event.respondWith(handleBundledAssetFetch(request, relPath));
    return;
  }}

  if (relPath === "version.json" || relPath === "manifest.json") {{
    event.respondWith(handleNetworkFirstShell(relPath));
    return;
  }}

  event.respondWith(handleCacheFirstShell(request, relPath));
}});
"""


