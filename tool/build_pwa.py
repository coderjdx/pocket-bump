def main():
    parser = argparse.ArgumentParser(description="Generate Pocket Bump PWA artifacts.")
    parser.add_argument("--web-dir", default="build/web")
    parser.add_argument("--version", required=True)
    parser.add_argument("--base-href", default="/pocket-bump/")
    args = parser.parse_args()

    web_dir = Path(args.web_dir).resolve()
    if not web_dir.is_dir():
        raise SystemExit(f"Web directory does not exist: {web_dir}")

    flutter_sw = web_dir / "flutter_service_worker.js"
    if flutter_sw.exists():
        flutter_sw.unlink()

    patch_manifest_json(web_dir, args.base_href)
    patch_index_html(web_dir)

    (
        core_assets,
        canvaskit_default,
        canvaskit_chromium,
        asset_manifest,
        build_hash,
    ) = collect_files(web_dir, args.version)

    cache_version = f"{args.version}-{build_hash}"
    sw_content = build_sw_js(
        cache_version=cache_version,
        core_assets=core_assets,
        canvaskit_default=canvaskit_default,
        canvaskit_chromium=canvaskit_chromium,
        asset_manifest=asset_manifest,
    )
    (web_dir / "sw.js").write_text(sw_content, encoding="utf-8")

    print(
        f"Generated PWA: version={cache_version}, "
        f"core={len(core_assets)}, ck_default={len(canvaskit_default)}, "
        f"ck_chromium={len(canvaskit_chromium)}, assets={len(asset_manifest)}"
    )


if __name__ == "__main__":
    main()
